# Fetch the third-party files this tree uses but does not ship.
#
# The release redistributes no third-party code, so what the gates and the review
# site need from other projects is downloaded here, each at a pinned version and
# checked against a pinned sha256 before it is kept:
#
#   vendor/wheels/       hypothesis 6.79.4 (MPL-2.0) and the three wheels it needs,
#                        attrs 23.2.0 (MIT), exceptiongroup 1.2.0 (MIT) and
#                        sortedcontainers 2.4.0 (Apache-2.0), from PyPI: the fuzzer
#                        the G-CONF containers install offline (docker_exec.py)
#   viz/static/vendor/   htmx 2.0.4 (0BSD), from unpkg, and pygments.css, the
#                        `default` style generated by the installed Pygments
#                        (BSD-2-Clause), which needs the `viz` extra
#
#   bash scripts/fetch_vendor.sh           # both
#   bash scripts/fetch_vendor.sh wheels    # only what the gates need
#   bash scripts/fetch_vendor.sh viz       # only what the review site needs
#
# PYTHON names the interpreter used for pip and Pygments (default: python3).
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
PYTHON="${PYTHON:-python3}"
HTMX_URL="https://unpkg.com/htmx.org@2.0.4/dist/htmx.min.js"
HTMX_SHA256="e209dda5c8235479f3166defc7750e1dbcd5a5c1808b7792fc2e6733768fb447"

wheels() {
  local dir="$ROOT/vendor/wheels" req
  mkdir -p "$dir"
  req="$(mktemp)"
  cat > "$req" <<'EOF'
attrs==23.2.0 --hash=sha256:99b87a485a5820b23b879f04c2305b44b951b502fd64be915879d77a7e8fc6f1
exceptiongroup==1.2.0 --hash=sha256:4bfd3996ac73b41e9b9628b04e079f193850720ea5945fc96a08633c66912f14
hypothesis==6.79.4 --hash=sha256:5ce05bc70aa4f20114effaf3375dc8b51d09a04026a0cf89d4514fc0b69f6304
sortedcontainers==2.4.0 --hash=sha256:a163dcaede0f1c021485e957a39245190e74249897e2ae4b2aa38595db237ee0
EOF
  "$PYTHON" -m pip download --quiet --no-deps --only-binary=:all: --require-hashes \
    -r "$req" -d "$dir" || { rm -f "$req"; echo "fetch_vendor: pip download failed" >&2; exit 1; }
  rm -f "$req"
  echo "fetch_vendor: wheels in $dir"
}

viz() {
  local dir="$ROOT/viz/static/vendor" tmp
  mkdir -p "$dir"
  tmp="$(mktemp)"
  curl -fsSL "$HTMX_URL" -o "$tmp" || { rm -f "$tmp"; echo "fetch_vendor: could not download $HTMX_URL" >&2; exit 1; }
  if ! "$PYTHON" - "$tmp" "$HTMX_SHA256" <<'EOF'
import hashlib, sys
path, want = sys.argv[1], sys.argv[2]
sys.exit(hashlib.sha256(open(path, "rb").read()).hexdigest() != want)
EOF
  then
    rm -f "$tmp"
    echo "fetch_vendor: $HTMX_URL does not match its pinned sha256" >&2
    exit 1
  fi
  mv "$tmp" "$dir/htmx.min.js"
  "$PYTHON" - "$dir/pygments.css" <<'EOF' || { echo "fetch_vendor: pygments.css needs Pygments (the viz extra)" >&2; exit 1; }
import sys
from pygments.formatters import HtmlFormatter
with open(sys.argv[1], "w", encoding="utf-8") as out:
    out.write(HtmlFormatter(style="default").get_style_defs(".highlight"))
EOF
  echo "fetch_vendor: review-site assets in $dir"
}

case "${1:-all}" in
  all) wheels; viz ;;
  wheels) wheels ;;
  viz) viz ;;
  *) echo "usage: fetch_vendor.sh [all|wheels|viz]" >&2; exit 2 ;;
esac
